    title_shape = s.shapes.title
    title_shape.text = title
    
    body_shape = s.shapes.placeholders[1]
    tf = body_shape.text_frame
    tf.word_wrap = True
    
    for idx, b in enumerate(bullets):
        if idx == 0:
            p = tf.paragraphs[0]
        else:
            p = tf.add_paragraph()
        p.text = b
        p.font.size = Pt(16)
        if b.startswith("•") or b.startswith("1.") or b.startswith("2.") or b.startswith("3.") or b.startswith("4.") or b.startswith("01") or b.startswith("02") or b.startswith("03"):
            p.font.bold = True

